
%% EMC-GUARD Stage 14B: MATLAB reference export
clear; clc;

integrationDir = fileparts(mfilename('fullpath'));
projectDir = fileparts(integrationDir);
modelRoot = fileparts(projectDir);

addpath(modelRoot);

inputFile = fullfile(integrationDir, 'input', ...
    'EMC_GUARD_Input.csv');

outputDir = fullfile(integrationDir, 'matlab_output');
if ~exist(outputDir, 'dir')
    mkdir(outputDir);
end

outputFile = fullfile(outputDir, ...
    'EMC_GUARD_MATLAB_Reference.csv');

assert(isfile(inputFile), ...
    'Input CSV not found: %s', inputFile);

T = readtable(inputFile);

required = {'Config_ID', 'PairSeparation_mm', ...
    'PairPitch_mm', 'Overlap_mm', 'GroundClearance_mm'};

assert(all(ismember(required, T.Properties.VariableNames)), ...
    'Input CSV is missing required columns.');

n = height(T);

Capacitance_pF_per_m = zeros(n,1);
AbsMutualInductance_nH = zeros(n,1);
DesignIndex = zeros(n,1);
CapacitanceModel = strings(n,1);
MutualInductanceModel = strings(n,1);
ValidationDomain = strings(n,1);

for k = 1:n
    r = EMC_GUARD_Predict( ...
        T.PairSeparation_mm(k), ...
        T.PairPitch_mm(k), ...
        T.Overlap_mm(k), ...
        T.GroundClearance_mm(k));

    Capacitance_pF_per_m(k) = r.Capacitance_pF_per_m;
    AbsMutualInductance_nH(k) = r.AbsMutualInductance_nH;
    DesignIndex(k) = r.DesignIndex;
    CapacitanceModel(k) = string(r.CapacitanceModel);
    MutualInductanceModel(k) = string(r.MutualInductanceModel);
    ValidationDomain(k) = string(r.ValidationDomain);
end

Reference = table( ...
    T.Config_ID, ...
    T.PairSeparation_mm, ...
    T.PairPitch_mm, ...
    T.Overlap_mm, ...
    T.GroundClearance_mm, ...
    Capacitance_pF_per_m, ...
    AbsMutualInductance_nH, ...
    DesignIndex, ...
    CapacitanceModel, ...
    MutualInductanceModel, ...
    ValidationDomain, ...
    'VariableNames', {'Config_ID', ...
    'PairSeparation_mm', 'PairPitch_mm', ...
    'Overlap_mm', 'GroundClearance_mm', ...
    'Capacitance_pF_per_m', ...
    'AbsMutualInductance_nH', ...
    'DesignIndex', 'CapacitanceModel', ...
    'MutualInductanceModel', 'ValidationDomain'});

writetable(Reference, outputFile);

fprintf('\nEMC-GUARD Stage 14B MATLAB export complete.\n');
fprintf('Configurations exported: %d\n', n);
fprintf('Output: %s\n', outputFile);
disp(Reference);
