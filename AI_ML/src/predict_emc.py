# ---------------------------------------------------------------------------
# PATHS
# ---------------------------------------------------------------------------
BASE_DIR    = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODEL_PKL   = os.path.join(BASE_DIR, "models", "emc_surrogate_model.pkl")
PREPROC_PKL = os.path.join(BASE_DIR, "models", "emc_preprocessor.pkl")
META_JSON   = os.path.join(BASE_DIR, "models", "target_model_metadata.json")
DATASET     = os.path.join(BASE_DIR, "dataset", "EMC_GUARD_Physics_Dataset.csv")

# ---------------------------------------------------------------------------
# COLUMN DEFINITIONS (must match train_model.py exactly)
# ---------------------------------------------------------------------------
NUMERICAL_FEATURES   = [
    "Separation_mm", "Overlap_mm", "Cable_Length_mm", "Frequency_Hz",
    "Voltage_V", "Conductor_Radius_mm", "Dielectric_Constant",
]
CATEGORICAL_FEATURES = ["Shield_Type", "Cable_Configuration"]
INPUT_FEATURES       = NUMERICAL_FEATURES + CATEGORICAL_FEATURES

# Known valid categorical values
VALID_SHIELD_TYPES  = {"Shielded", "Unshielded"}
VALID_CABLE_CONFIGS = {"Parallel", "Perpendicular", "Crossed"}

# Training range bounds (populated at load time from dataset)
_TRAINING_BOUNDS: dict = {}


# ---------------------------------------------------------------------------
# TRAINING RANGE INITIALISATION
# ---------------------------------------------------------------------------

def _load_training_bounds():
    """
    Read the cleaned dataset once and cache feature min/max values
    for out-of-domain warnings. Called lazily on first predict.
    """
    global _TRAINING_BOUNDS
    if _TRAINING_BOUNDS:
        return   # already loaded
    try:
        df = pd.read_csv(DATASET)
        for col in NUMERICAL_FEATURES:
            if col in df.columns:
                _TRAINING_BOUNDS[col] = {
                    "min": float(df[col].min()),
                    "max": float(df[col].max()),
                }
    except Exception:
        pass     # bounds checking will be skipped silently


# ---------------------------------------------------------------------------
# INPUT VALIDATION
# ---------------------------------------------------------------------------

class ValidationError(ValueError):
    """Raised when the input configuration fails validation."""


def validate_configuration(config: dict) -> list:
    """
    Validate the input configuration dictionary.

    Parameters
    ----------
    config : dict
        Raw input configuration from the caller.

    Returns
    -------
    list of str
        Warning messages (non-fatal). Empty list = no warnings.

    Raises
    ------
    ValidationError
        If a fatal validation rule is violated.
    """
    warnings_out = []

    # 1. Check all required features are present
    missing = [f for f in INPUT_FEATURES if f not in config]
    if missing:
        raise ValidationError(
            f"Missing required input features: {missing}\n"
            f"Required features: {INPUT_FEATURES}"
        )

    # 2. Validate numerical features are numeric and positive where required
    strictly_positive = {
        "Separation_mm", "Overlap_mm", "Cable_Length_mm",
        "Frequency_Hz", "Voltage_V", "Conductor_Radius_mm", "Dielectric_Constant"
    }
    for col in NUMERICAL_FEATURES:
        val = config[col]
        if not isinstance(val, (int, float)):
            raise ValidationError(
                f"Feature '{col}' must be numeric. Received: {type(val).__name__}"
            )
        if np.isnan(float(val)) or np.isinf(float(val)):
            raise ValidationError(
                f"Feature '{col}' contains NaN or Inf. Received: {val}"
            )
        if col in strictly_positive and float(val) <= 0:
            raise ValidationError(
                f"Feature '{col}' must be strictly positive. Received: {val}"
            )

    # 3. Validate categorical features
    st = str(config["Shield_Type"])
    cc = str(config["Cable_Configuration"])

    if st not in VALID_SHIELD_TYPES:
        warnings_out.append(
            f"[WARN] Unfamiliar Shield_Type='{st}'. "
            f"Trained on: {VALID_SHIELD_TYPES}. "
            "Prediction may be unreliable."
        )
    if cc not in VALID_CABLE_CONFIGS:
        warnings_out.append(
            f"[WARN] Unfamiliar Cable_Configuration='{cc}'. "
            f"Trained on: {VALID_CABLE_CONFIGS}. "
            "Prediction may be unreliable."
        )

    # 4. Out-of-domain numerical warnings
    _load_training_bounds()
    for col in NUMERICAL_FEATURES:
        if col not in _TRAINING_BOUNDS:
            continue
        val = float(config[col])
        lo  = _TRAINING_BOUNDS[col]["min"]
        hi  = _TRAINING_BOUNDS[col]["max"]
        if val < lo or val > hi:
            warnings_out.append(
                f"[WARN] '{col}'={val} is outside the training range "
                f"[{lo:.3f}, {hi:.3f}]. Extrapolation — use with caution."
            )

    return warnings_out


# ---------------------------------------------------------------------------
# MODEL LOADING
# ---------------------------------------------------------------------------

def _load_models():
    """
    Load and return (preprocessor, surrogate_bundle, metadata).
    Exits with a clear message if any artefact is missing.
    """
    for path, label in [(MODEL_PKL,   "emc_surrogate_model.pkl"),
                        (PREPROC_PKL, "emc_preprocessor.pkl"),
                        (META_JSON,   "target_model_metadata.json")]:
        if not os.path.exists(path):
            print(f"[ERROR] Model artefact not found: {path}")
            print("  Run 'python src/train_model.py' first.")
            sys.exit(1)

    preprocessor     = joblib.load(PREPROC_PKL)
    surrogate_bundle = joblib.load(MODEL_PKL)
    with open(META_JSON) as f:
        metadata = json.load(f)
    return preprocessor, surrogate_bundle, metadata


# ---------------------------------------------------------------------------
# PRIMARY PREDICTION API
# ---------------------------------------------------------------------------

def predict_interference(configuration: dict,
                          verbose: bool = False) -> dict:
    """
    Predict electromagnetic interference outputs for a given cable configuration.

    Parameters
    ----------
    configuration : dict
        Dictionary containing all required input features:
            Separation_mm, Overlap_mm, Cable_Length_mm, Frequency_Hz,
            Voltage_V, Conductor_Radius_mm, Dielectric_Constant,
            Shield_Type, Cable_Configuration

    verbose : bool
        If True, print warnings and predictions to stdout.

    Returns
    -------
    dict
        {
          "predictions": {target: float, ...},
          "warnings":    [str, ...],
          "model_info":  {target: {"algorithm": str, "R2": float}, ...}
        }

    Raises
    ------
    ValidationError
        If the configuration has missing or invalid values.

    Example
    -------
    >>> config = {
    ...     "Separation_mm": 20, "Overlap_mm": 450, "Cable_Length_mm": 450,
    ...     "Frequency_Hz": 100000, "Voltage_V": 24,
    ...     "Conductor_Radius_mm": 0.5, "Dielectric_Constant": 2.3,
    ...     "Shield_Type": "Unshielded", "Cable_Configuration": "Parallel"
    ... }
    >>> result = predict_interference(config, verbose=True)
    """
    # Step 1: Validate
    input_warnings = validate_configuration(configuration)

    if verbose and input_warnings:
        for w in input_warnings:
            print(w)

    # Step 2: Load artefacts
    preprocessor, surrogate_bundle, metadata = _load_models()

    # Step 3: Build input DataFrame (single row)
    row = {feat: [configuration[feat]] for feat in INPUT_FEATURES}
    X_df = pd.DataFrame(row)

    # Step 4: Transform
    X_enc = preprocessor.transform(X_df)

    # Step 5: Predict for each available target
    predictions = {}
    model_info  = {}

    for target, bundle in surrogate_bundle.items():
        model    = bundle["model"]
        algo     = bundle["algorithm"]
        y_pred   = model.predict(X_enc)[0]
        # Clip to physically reasonable range (non-negative for EM quantities)
        y_pred   = float(max(0.0, y_pred))
        predictions[target] = round(y_pred, 8)
        model_info[target]  = {
            "algorithm": algo,
            "R2":        metadata.get(target, {}).get("R2", None),
        }

    result = {
        "predictions": predictions,
        "warnings":    input_warnings,
        "model_info":  model_info,
    }

    if verbose:
        _print_prediction_result(result, configuration)

    return result


# ---------------------------------------------------------------------------
# PRETTY PRINT
# ---------------------------------------------------------------------------

def _print_prediction_result(result: dict, config: dict):
    sep = "=" * 60
    print(sep)
    print("EMC-GUARD PREDICTION RESULT")
    print("[SYNTHETIC DATA — experimental result only]")
    print(sep)
    print("\nInput Configuration:")
    for k, v in config.items():
        print(f"  {k:<25s}: {v}")
    print()
    if result["warnings"]:
        print("Warnings:")
        for w in result["warnings"]:
            print(f"  {w}")
        print()
    print("Predicted EMC Outputs:")
    print("-" * 60)
    for target, value in result["predictions"].items():
        algo = result["model_info"][target]["algorithm"]
        r2   = result["model_info"][target]["R2"]
        r2_s = f"{r2:.4f}" if r2 is not None else "N/A"
        print(f"  {target:<26}: {value:.8f}   [{algo}, R2={r2_s}]")
    print(sep)
    print("DISCLAIMER: These predictions are from a model trained on")
    print("SYNTHETIC DUMMY DATA. They are NOT validated EMC measurements.")
    print(sep)


