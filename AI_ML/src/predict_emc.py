def run_self_tests():
    """
    Task 11: Run a suite of validation and prediction tests.
    Tests:
      T1 — Valid in-domain configuration
      T2 — Missing key (should raise ValidationError)
      T3 — Negative frequency (should raise ValidationError)
      T4 — Unseen categorical value (should warn, not crash)
      T5 — Out-of-domain numerical input (should warn, not crash)
      T6 — Model reload in independent function scope (persistence check)
    """
    PASS = "[PASS]"
    FAIL = "[FAIL]"

    sep = "=" * 60
    print(sep)
    print("EMC-GUARD  |  Module 2  |  Prediction Engine Self-Test")
    print("[Results based on SYNTHETIC DATA — experimental only]")
    print(sep)

    # T1 — Valid configuration
    print("\n[T1] Valid in-domain configuration ...")
    valid_config = {
        "Separation_mm":       20.0,
        "Overlap_mm":         450.0,
        "Cable_Length_mm":    450.0,
        "Frequency_Hz":    100000.0,
        "Voltage_V":           24.0,
        "Conductor_Radius_mm":  0.5,
        "Dielectric_Constant":  2.3,
        "Shield_Type":     "Unshielded",
        "Cable_Configuration": "Parallel",
    }
    try:
        result = predict_interference(valid_config, verbose=True)
        targets_ok = all(t in result["predictions"] for t in
                         ["MutualInductance_nH", "MutualCapacitance_pF",
                          "Victim_Voltage_V", "Victim_RMS_V", "Victim_PeakToPeak_V"])
        print(f"  {PASS if targets_ok else FAIL} All target keys present: {targets_ok}")
    except Exception as e:
        print(f"  {FAIL} Unexpected exception: {e}")

    # T2 — Missing required key
    print("\n[T2] Missing required input key ...")
    bad_config = {k: v for k, v in valid_config.items() if k != "Frequency_Hz"}
    try:
        predict_interference(bad_config)
        print(f"  {FAIL} No exception raised — should have raised ValidationError.")
    except ValidationError as e:
        print(f"  {PASS} ValidationError raised correctly:")
        print(f"         {str(e)[:120]}")
    except Exception as e:
        print(f"  {FAIL} Wrong exception type ({type(e).__name__}): {e}")

    # T3 — Invalid numerical value (negative frequency)
    print("\n[T3] Invalid numerical value (negative Frequency_Hz) ...")
    neg_config = dict(valid_config)
    neg_config["Frequency_Hz"] = -500.0
    try:
        predict_interference(neg_config)
        print(f"  {FAIL} No exception raised — should have raised ValidationError.")
    except ValidationError as e:
        print(f"  {PASS} ValidationError raised correctly:")
        print(f"         {str(e)[:120]}")
    except Exception as e:
        print(f"  {FAIL} Wrong exception type ({type(e).__name__}): {e}")

    # T4 — Unfamiliar categorical value
    print("\n[T4] Unfamiliar categorical value (Shield_Type='Braided') ...")
    cat_config = dict(valid_config)
    cat_config["Shield_Type"] = "Braided"
    try:
        result = predict_interference(cat_config, verbose=False)
        warned = any("Shield_Type" in w for w in result["warnings"])
        preds  = result["predictions"]
        print(f"  {PASS if warned else FAIL} Warning raised for unseen category: {warned}")
        print(f"  {PASS if preds else FAIL} Prediction still produced: {bool(preds)}")
        if preds:
            print(f"         Sample: MutualInductance_nH = "
                  f"{preds.get('MutualInductance_nH', 'N/A'):.8f}")
    except Exception as e:
        print(f"  {FAIL} Unexpected exception: {e}")

    # T5 — Out-of-domain numerical input
    print("\n[T5] Out-of-domain numerical input (Separation_mm=99999 mm) ...")
    ood_config = dict(valid_config)
    ood_config["Separation_mm"] = 99999.0
    try:
        result = predict_interference(ood_config, verbose=False)
        warned = any("Separation_mm" in w for w in result["warnings"])
        preds  = result["predictions"]
        print(f"  {PASS if warned else FAIL} Out-of-domain warning raised: {warned}")
        print(f"  {PASS if preds else FAIL} Prediction still produced (extrapolation): "
              f"{bool(preds)}")
    except ValidationError as e:
        print(f"  {FAIL} ValidationError raised unexpectedly: {e}")
    except Exception as e:
        print(f"  {FAIL} Unexpected exception: {e}")

    # T6 — Model persistence (reload in independent scope)
    print("\n[T6] Model persistence — reloading in fresh function scope ...")
    try:
        _verify_persistence(valid_config)
    except Exception as e:
        print(f"  {FAIL} Persistence check failed: {e}")

    print(f"\n{sep}")
    print("[DONE] All self-tests complete.")
    print(sep)


def _verify_persistence(config: dict):
    """
    Simulate a separate Python process by clearing module-level caches
    and reloading from disk.  Confirms the pkl files are self-contained.
    """
    import importlib
    # Reload the pkl explicitly (mimics a fresh Python session)
    preprocessor     = joblib.load(PREPROC_PKL)
    surrogate_bundle = joblib.load(MODEL_PKL)
    with open(META_JSON) as f:
        metadata = json.load(f)

    X_df = pd.DataFrame({feat: [config[feat]] for feat in INPUT_FEATURES})
    X_enc = preprocessor.transform(X_df)

    predictions = {}
    for target, bundle in surrogate_bundle.items():
        y_pred = bundle["model"].predict(X_enc)[0]
        predictions[target] = round(float(y_pred), 8)

    assert len(predictions) > 0, "No predictions produced after reload."
    print(f"  [PASS] Models reloaded successfully. Targets: {list(predictions.keys())}")
    print(f"         Sample MutualInductance_nH = "
          f"{predictions.get('MutualInductance_nH', 'N/A')}")


