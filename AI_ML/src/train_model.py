def main():
    print("=" * 68)
    print("EMC-GUARD  |  Module 2  |  Surrogate Model Training Pipeline")
    print("=" * 68)

    os.makedirs(MODELS_DIR, exist_ok=True)
    os.makedirs(REPORTS, exist_ok=True)
    os.makedirs(VIS_DIR, exist_ok=True)

    evaluation_date = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    # -------- Step 1: Load -----------------------------------------------
    print("\n[1/9] Loading and validating dataset ...")
    df, dataset_type, active_targets = load_and_validate(DATASET)

    if dataset_type == "SYNTHETIC":
        print("\n  [INFO] SYNTHETIC DUMMY DATA detected.")
        print("  All model results are labelled as experimental / non-validated.")

    # -------- Step 2: Fit global preprocessor on full training data -------
    # We fit one shared preprocessor on the union of all training rows so
    # the pkl is identical regardless of which target is being predicted.
    print("\n[2/9] Fitting shared preprocessing pipeline on training data ...")
    X_full = df[INPUT_FEATURES]
    y_dummy = df[active_targets[0]]   # dummy target just for split index
    X_train_raw, X_test_raw, _, _ = train_test_split(
        X_full, y_dummy, test_size=TEST_SIZE, random_state=RANDOM_STATE
    )
    preprocessor = build_preprocessor()
    preprocessor.fit(X_train_raw)
    X_train_enc = preprocessor.transform(X_train_raw)
    X_test_enc  = preprocessor.transform(X_test_raw)
    print(f"  Training encoded shape : {X_train_enc.shape}")
    print(f"  Testing  encoded shape : {X_test_enc.shape}")

    # Save shared preprocessor
    joblib.dump(preprocessor, PREPROC_PKL)
    print(f"  Saved preprocessor: models/emc_preprocessor.pkl")

    # -------- Steps 3-6: Train, evaluate, select best (per target) --------
    target_results   = {}
    comparison_rows  = []
    all_pred_rows    = []
    surrogate_bundle = {}    # {target: {"algo": name, "model": fitted_model}}
    metadata         = {}

    total_train = len(X_train_raw)
    total_test  = len(X_test_raw)

    for tgt in active_targets:
        print(f"\n[3-6] Target: {tgt}")

        # Per-target split (align rows using the same global split indices)
        sub       = df.dropna(subset=[tgt])
        X_sub     = sub[INPUT_FEATURES].reset_index(drop=True)
        y_sub     = sub[tgt].reset_index(drop=True)
        Xtr, Xte, ytr, yte = train_test_split(
            X_sub, y_sub, test_size=TEST_SIZE, random_state=RANDOM_STATE
        )
        Xtr_enc = preprocessor.transform(Xtr)
        Xte_enc = preprocessor.transform(Xte)

        # Train
        models = train_models(Xtr_enc, ytr)

        # Evaluate
        res = {"y_test": yte.tolist()}
        for algo_name, model in models.items():
            metrics = evaluate_model(model, Xte_enc, yte, tgt, algo_name)
            res[algo_name] = metrics
            comparison_rows.append({
                "Target":    tgt,
                "Algorithm": algo_name,
                "MAE":       metrics["MAE"],
                "RMSE":      metrics["RMSE"],
                "R2":        metrics["R2"],
            })
            print(f"    {algo_name:<16}  MAE={metrics['MAE']:.6f}  "
                  f"RMSE={metrics['RMSE']:.6f}  R2={metrics['R2']:.6f}")

        # Select best
        best_algo = select_best(res)
        res["best_algo"] = best_algo
        target_results[tgt] = res
        print(f"    --> Best: {best_algo}")

        # Store best model in bundle
        surrogate_bundle[tgt] = {
            "algorithm": best_algo,
            "model":     models[best_algo],
        }

        # Metadata
        best_m = res[best_algo]
        metadata[tgt] = {
            "best_algorithm": best_algo,
            "MAE":  best_m["MAE"],
            "RMSE": best_m["RMSE"],
            "R2":   best_m["R2"],
        }

        # Collect prediction rows for prediction_results.csv
        y_pred_best = np.array(res[best_algo]["y_pred"])
        y_test_arr  = np.array(yte.tolist())
        for actual, predicted in zip(y_test_arr, y_pred_best):
            all_pred_rows.append({
                "Target": tgt,
                "Algorithm": best_algo,
                "Actual": actual,
                "Predicted": predicted,
                "Residual": predicted - actual,
            })

    # -------- Step 7: Save models ----------------------------------------
    print("\n[7/9] Saving model artefacts ...")
    joblib.dump(surrogate_bundle, MODEL_PKL)
    print(f"  Saved: models/emc_surrogate_model.pkl")

    with open(METADATA_JSON, "w") as f:
        json.dump(metadata, f, indent=2)
    print(f"  Saved: models/target_model_metadata.json")

    # prediction_results.csv
    pd.DataFrame(all_pred_rows).to_csv(PRED_CSV, index=False)
    print(f"  Saved: reports/prediction_results.csv")

    # -------- Step 9: Visualisations -------------------------------------
