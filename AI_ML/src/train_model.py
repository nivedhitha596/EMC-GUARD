def plot_metric_comparison(comparison_df: pd.DataFrame, metric: str, fig_num: int):
    """Grouped bar chart: RF vs ET for a given metric across all targets."""
    fig, ax = plt.subplots(figsize=(max(10, len(comparison_df) * 1.2), 5))
    targets    = comparison_df["Target"].unique().tolist()
    algorithms = comparison_df["Algorithm"].unique().tolist()
    x          = np.arange(len(targets))
    width      = 0.35
    palette    = {"Random Forest": "#2196F3", "Extra Trees": "#FF9800"}

    for k, algo in enumerate(algorithms):
        vals = comparison_df[comparison_df["Algorithm"] == algo].set_index("Target")[metric]
        vals = [vals.get(t, 0) for t in targets]
        offset = (k - 0.5) * width
        bars = ax.bar(x + offset, vals, width, label=algo,
                      color=palette.get(algo, "grey"), edgecolor="black", linewidth=0.5)
        for bar, v in zip(bars, vals):
            ax.text(bar.get_x() + bar.get_width() / 2, bar.get_height(),
                    f"{v:.4f}", ha="center", va="bottom", fontsize=7, rotation=45)

    ax.set_xticks(x)
    ax.set_xticklabels(targets, rotation=25, ha="right", fontsize=9)
    ax.set_ylabel(metric)
    ax.set_title(f"{metric} Comparison: Random Forest vs Extra Trees{SYNTH_NOTE}",
                 fontsize=10)
    ax.legend()
    fig.tight_layout()
    save_fig(fig, f"{fig_num}_{metric.lower().replace(' ', '_')}_comparison.png")


