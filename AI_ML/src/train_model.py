def plot_actual_vs_predicted(target_results: dict):
    """Actual vs Predicted scatter — one subplot per target."""
    targets = list(target_results.keys())
    ncols = min(3, len(targets))
    nrows = (len(targets) + ncols - 1) // ncols
    fig, axes = plt.subplots(nrows, ncols, figsize=(6 * ncols, 5 * nrows))
    axes = np.array(axes).flatten()

    for i, tgt in enumerate(targets):
        best_algo = target_results[tgt]["best_algo"]
        y_test    = np.array(target_results[tgt]["y_test"])
        y_pred    = np.array(target_results[tgt][best_algo]["y_pred"])
        r2        = target_results[tgt][best_algo]["R2"]

        ax = axes[i]
        ax.scatter(y_test, y_pred, alpha=0.45, s=18, color="steelblue", edgecolors="none")
        mn = min(y_test.min(), y_pred.min())
        mx = max(y_test.max(), y_pred.max())
        ax.plot([mn, mx], [mn, mx], "r--", lw=1.5, label="Perfect fit")
        ax.set_xlabel(f"Actual {tgt}", fontsize=9)
        ax.set_ylabel("Predicted", fontsize=9)
        ax.set_title(f"{tgt}\n{best_algo}  R²={r2:.4f}", fontsize=9)
        ax.legend(fontsize=8)

    for j in range(i + 1, len(axes)):
        axes[j].set_visible(False)

    fig.suptitle("Actual vs Predicted" + SYNTH_NOTE, fontsize=11, y=1.01)
    fig.tight_layout()
    save_fig(fig, "11_actual_vs_predicted.png")


