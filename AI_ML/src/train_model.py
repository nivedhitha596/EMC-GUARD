def build_preprocessor() -> ColumnTransformer:
    """Build the same ColumnTransformer used in Module 1 so inference is consistent."""
    num_pipe = Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler",  StandardScaler()),
    ])
    cat_pipe = Pipeline([
        ("imputer", SimpleImputer(strategy="most_frequent")),
        ("encoder", OneHotEncoder(drop="first", sparse_output=False,
                                  handle_unknown="ignore")),
    ])
    return ColumnTransformer([
        ("numerical",   num_pipe, NUMERICAL_FEATURES),
        ("categorical", cat_pipe, CATEGORICAL_FEATURES),
    ], remainder="drop")


def prepare_split(df: pd.DataFrame, target: str):
    """
    Return (X_train_raw, X_test_raw, y_train, y_test) for one target.
    Rows with NaN in the target are dropped before splitting.
    """
    sub = df.dropna(subset=[target])
    X   = sub[INPUT_FEATURES].reset_index(drop=True)
    y   = sub[target].reset_index(drop=True)
    return train_test_split(X, y, test_size=TEST_SIZE, random_state=RANDOM_STATE)


# ============================================================
# STEP 3 & 4 — TRAIN MODELS
# ============================================================

def train_models(X_train_enc: np.ndarray, y_train: pd.Series) -> dict:
    """Train RF and ET on encoded training data. Returns dict of fitted models."""
    print("    Fitting Random Forest  ...", end=" ", flush=True)
    rf = RandomForestRegressor(**RF_PARAMS)
    rf.fit(X_train_enc, y_train)
    print("done")

    print("    Fitting Extra Trees    ...", end=" ", flush=True)
    et = ExtraTreesRegressor(**ET_PARAMS)
    et.fit(X_train_enc, y_train)
    print("done")

    return {"Random Forest": rf, "Extra Trees": et}


# ============================================================
# STEP 5 — EVALUATE
# ============================================================

def evaluate_model(model, X_test_enc: np.ndarray, y_test: pd.Series,
                   target: str, algo_name: str) -> dict:
    """Return MAE, RMSE, R2 for a single model on the test set."""
    y_pred = model.predict(X_test_enc)
    mae    = mean_absolute_error(y_test, y_pred)
    rmse   = np.sqrt(mean_squared_error(y_test, y_pred))
    r2     = r2_score(y_test, y_pred)
    return {
        "target":     target,
        "algorithm":  algo_name,
        "MAE":        round(float(mae),  6),
        "RMSE":       round(float(rmse), 6),
        "R2":         round(float(r2),   6),
        "y_pred":     y_pred.tolist(),
    }


# ============================================================
# STEP 6 — SELECT BEST MODEL PER TARGET
# ============================================================

def select_best(results: dict) -> str:
    """
    Compare RF vs ET for one target on the test set.
    Priority: higher R2, then lower RMSE.
    Returns the name of the better algorithm.
    """
    rf_r2   = results["Random Forest"]["R2"]
    et_r2   = results["Extra Trees"]["R2"]
    rf_rmse = results["Random Forest"]["RMSE"]
    et_rmse = results["Extra Trees"]["RMSE"]

    if rf_r2 > et_r2:
        return "Random Forest"
    elif et_r2 > rf_r2:
        return "Extra Trees"
    else:  # tie on R2 — use RMSE as tiebreak
        return "Random Forest" if rf_rmse <= et_rmse else "Extra Trees"


