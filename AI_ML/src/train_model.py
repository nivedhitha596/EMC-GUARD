def detect_dataset_type(df: pd.DataFrame) -> str:
    """
    Heuristic: if Configuration_IDs contain 'CFG_' prefix introduced by
    generate_dummy_data.py the dataset is synthetic.
    Returns 'SYNTHETIC' or 'MATLAB'.
    """
    if "Configuration_ID" in df.columns:
        ids = df["Configuration_ID"].astype(str)
        if ids.str.startswith("CFG_").any():
            return "SYNTHETIC"
    return "MATLAB"


def load_and_validate(path: str) -> tuple:
    """
    Load the cleaned dataset and validate it for Module 2 training.
    Returns (df, dataset_type, active_targets).
    Exits with a clear message if critical columns are missing.
    """
    print(f"  Loading: {os.path.relpath(path, BASE_DIR)}")
    if not os.path.exists(path):
        print(f"[ERROR] Dataset not found: {path}")
        print("  Run Module 1 (data_cleaning.py) first.")
        sys.exit(1)

    df = pd.read_csv(path)
    print(f"  Shape  : {df.shape[0]} rows x {df.shape[1]} columns")

    # Check required input feature columns
    missing_inputs = [c for c in INPUT_FEATURES if c not in df.columns]
    if missing_inputs:
        print(f"[ERROR] Missing required input columns: {missing_inputs}")
        sys.exit(1)

    # Determine which targets have enough valid records
    active_targets = []
    skipped_targets = []
    for col in TARGET_COLS:
        if col not in df.columns:
            skipped_targets.append((col, "column absent"))
            continue
        valid_n = df[col].notna().sum()
        if valid_n < MIN_VALID_RECORDS:
            skipped_targets.append((col, f"only {valid_n} valid records"))
        else:
            active_targets.append(col)

    if not active_targets:
        print("[ERROR] No targets with sufficient valid records found. Exiting.")
        sys.exit(1)

    dataset_type = detect_dataset_type(df)

    print(f"\n  Dataset type     : {dataset_type}")
    print(f"  Active targets   : {active_targets}")
    if skipped_targets:
        for t, reason in skipped_targets:
            print(f"  Skipped target   : {t}  ({reason})")

    # Report missing values
    null_total = df[INPUT_FEATURES + active_targets].isnull().sum().sum()
    if null_total > 0:
        print(f"\n  [WARN] {null_total} residual NaN cells detected — "
              "imputer inside pipeline will handle them.")

    return df, dataset_type, active_targets


